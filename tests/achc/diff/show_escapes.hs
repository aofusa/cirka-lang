-- show of strings and chars with escapes, showString/shows/showParen
module Main where

main :: IO ()
main = do
  putStrLn (show "a\"b\n\tc")
  putStrLn (show '\'')
  putStrLn (show '"')
  putStrLn (show "'")
  putStrLn (show '\n')
  putStrLn (show '\\')
  putStrLn (show "back\\slash")
  putStrLn (show "\1234\&5")
  putStrLn (show "\SO\&H")
  putStrLn (show "\SOH")
  putStrLn (show "\200")
  putStrLn (show "tab\there")
  putStrLn (show "\233t\233")
  putStrLn (show '\0')
  putStrLn (show (maxBound :: Char))
  putStrLn (show "")
  putStrLn (show ["a", "b\"c"])
  putStrLn (show (Just "x\ny"))
  putStrLn (show (show "nested\"quote"))
  putStrLn (show ('a', "b", 'c'))
  putStrLn (shows (12 :: Int) " apples")
  putStrLn (showString "abc" "def")
  putStrLn (showParen True (shows (5 :: Int)) "")
  putStrLn (showParen False (shows (5 :: Int)) "!")
  putStrLn (show (length (show "\n\n")))
