//! cirka-codegen-llvm: MIR → LLVM IR text (07-backend.md).
//!
//! - every MIR function becomes a `tailcc` function; `tailcall` (and
//!   `let r = call/apply ...; ret r`) become `musttail` calls,
//! - dup/drop fast paths are inlined (release) or call the checking
//!   runtime functions (debug runtime),
//! - closures and thunks get generated entry stubs, and the generic
//!   eval/apply helpers `cirka_apply_1..8` are emitted into every module.

use cirka_mir::ir::*;
use std::collections::{BTreeMap, HashMap, HashSet};
use std::fmt::Write;

/// Code generation options.
#[derive(Clone, Copy, Debug, Default)]
pub struct Options {
    /// Call the checking runtime functions instead of inlining RC fast paths.
    pub debug_rt: bool,
}

/// Mangles a MIR function name into an LLVM global name.
pub fn mangle(name: &str) -> String {
    format!("@\"_C{}{}\"", name.len(), name.replace('"', "\\22"))
}

fn llty(t: Ty) -> &'static str {
    match t {
        Ty::Ptr => "ptr",
        Ty::I64 => "i64",
        Ty::I32 => "i32",
        Ty::I8 => "i8",
        Ty::F64 => "double",
    }
}

fn header_word(rc: i32, tag: u32, nptr: usize, kind: u8) -> u64 {
    (rc as u32 as u64)
        | ((tag as u64 & 0xffff) << 32)
        | ((nptr as u64 & 0xff) << 48)
        | ((kind as u64) << 56)
}

fn esc_bytes(b: &[u8]) -> String {
    let mut s = String::new();
    for &c in b {
        if (0x20..0x7f).contains(&c) && c != b'"' && c != b'\\' {
            s.push(c as char);
        } else {
            let _ = write!(s, "\\{c:02X}");
        }
    }
    s
}

/// Runtime functions and their LLVM signatures.
const RUNTIME_DECLS: &[(&str, &str)] = &[
    ("cirka_alloc", "ptr @cirka_alloc(i64)"),
    ("cirka_free_object", "void @cirka_free_object(ptr)"),
    ("cirka_free_raw", "void @cirka_free_raw(ptr)"),
    ("cirka_dup", "void @cirka_dup(ptr)"),
    ("cirka_drop", "void @cirka_drop(ptr)"),
    ("cirka_dec_ref_slow", "void @cirka_dec_ref_slow(ptr)"),
    ("cirka_drop_reuse", "ptr @cirka_drop_reuse(ptr)"),
    ("cirka_force", "ptr @cirka_force(ptr)"),
    ("cirka_mk_pap", "ptr @cirka_mk_pap(ptr, i64, ptr)"),
    ("cirka_panic", "void @cirka_panic(ptr, i64) noreturn"),
    ("cirka_bytes_new", "ptr @cirka_bytes_new(i64)"),
    ("cirka_array_new", "ptr @cirka_array_new(i64, ptr)"),
    (
        "llvm.fptosi.sat.i64.f64",
        "i64 @llvm.fptosi.sat.i64.f64(double)",
    ),
];

struct Gen<'m> {
    m: &'m Module,
    opts: Options,
    out: String,
    globals: String,
    strings: HashMap<Vec<u8>, String>,
    panics: HashMap<String, (String, usize)>,
    statics: HashMap<(u32, u32), String>,
    clo_stubs: BTreeMap<String, usize>,
    thunk_stubs: BTreeMap<String, ()>,
    funcs: HashMap<&'m str, &'m Function>,
    externs: BTreeMap<String, String>,
    label_counter: usize,
}

/// Generates the LLVM IR text of a whole program.
pub fn emit(m: &Module, opts: Options) -> String {
    let mut g = Gen {
        m,
        opts,
        out: String::new(),
        globals: String::new(),
        strings: HashMap::new(),
        panics: HashMap::new(),
        statics: HashMap::new(),
        clo_stubs: BTreeMap::new(),
        thunk_stubs: BTreeMap::new(),
        funcs: m.funcs.iter().map(|f| (f.name.as_str(), f)).collect(),
        externs: BTreeMap::new(),
        label_counter: 0,
    };
    for e in &m.externs {
        if RUNTIME_DECLS.iter().any(|(n, _)| *n == e.name) {
            continue;
        }
        let params: Vec<&str> = e.params.iter().map(|p| llty(p.0)).collect();
        g.externs.insert(
            e.name.clone(),
            format!(
                "{} @{}({})",
                e.ret.map(llty).unwrap_or("void"),
                e.name,
                params.join(", ")
            ),
        );
    }
    for f in &m.funcs {
        g.function(f);
    }
    for gl in &m.globals {
        g.thunk_stubs.insert(gl.init.clone(), ());
    }
    let clo: Vec<(String, usize)> = g.clo_stubs.iter().map(|(k, v)| (k.clone(), *v)).collect();
    for (f, ncap) in clo {
        g.closure_stub(&f, ncap);
    }
    let thk: Vec<String> = g.thunk_stubs.keys().cloned().collect();
    for f in thk {
        g.thunk_stub(&f);
    }
    for n in 1..=MAX_CLOSURE_ARITY {
        g.apply_helper(n);
    }
    g.entry_and_cafs();

    let mut s = String::new();
    s.push_str("; generated by cirka-codegen-llvm\n");
    s.push_str("target triple = \"x86_64-unknown-linux-gnu\"\n\n");
    for (_, d) in RUNTIME_DECLS {
        let _ = writeln!(s, "declare {d}");
    }
    for d in g.externs.values() {
        let _ = writeln!(s, "declare {d}");
    }
    s.push('\n');
    s.push_str(&g.globals);
    s.push('\n');
    s.push_str(&g.out);
    s
}

/// Emission state of one function body.
struct FnCtx<'a> {
    f: &'a Function,
    body: String,
    tmp: usize,
    /// Current LLVM block label.
    cur: String,
    /// phi incoming values per MIR block: (value list, predecessor label).
    phis: HashMap<usize, Vec<(Vec<String>, String)>>,
    tokens: HashSet<Var>,
}

impl FnCtx<'_> {
    fn t(&mut self) -> String {
        self.tmp += 1;
        format!("%t{}", self.tmp)
    }
    fn line(&mut self, s: &str) {
        self.body.push_str("  ");
        self.body.push_str(s);
        self.body.push('\n');
    }
    fn label(&mut self, l: &str) {
        let _ = writeln!(self.body, "{l}:");
        self.cur = l.to_string();
    }
}

fn var(v: Var) -> String {
    format!("%v{}", v.0)
}

fn bb_label(i: usize) -> String {
    format!("bb{i}")
}

impl<'m> Gen<'m> {
    fn fresh_label(&mut self, hint: &str) -> String {
        self.label_counter += 1;
        format!("{hint}{}", self.label_counter)
    }

    fn string_obj(&mut self, b: &[u8]) -> String {
        if let Some(n) = self.strings.get(b) {
            return n.clone();
        }
        let name = format!("@str.{}", self.strings.len());
        let len = b.len();
        let _ = writeln!(
            self.globals,
            "{name} = private global {{ i64, i64, [{len} x i8] }} {{ i64 {}, i64 {len}, [{len} x i8] c\"{}\" }}, align 8",
            header_word(0, 0, 0, kind::BYTES),
            esc_bytes(b)
        );
        self.strings.insert(b.to_vec(), name.clone());
        name
    }

    fn panic_msg(&mut self, msg: &str) -> (String, usize) {
        if let Some(p) = self.panics.get(msg) {
            return p.clone();
        }
        let name = format!("@panic.{}", self.panics.len());
        let len = msg.len();
        let _ = writeln!(
            self.globals,
            "{name} = private constant [{len} x i8] c\"{}\"",
            esc_bytes(msg.as_bytes())
        );
        self.panics.insert(msg.to_string(), (name.clone(), len));
        (name, len)
    }

    fn static_con(&mut self, c: CtorRef) -> String {
        if let Some(n) = self.statics.get(&(c.ty, c.ctor)) {
            return n.clone();
        }
        let name = format!("@con.{}.{}", c.ty, c.ctor);
        let _ = writeln!(
            self.globals,
            "{name} = private global i64 {}, align 8",
            header_word(0, self.m.ctor(c).tag, 0, kind::CON)
        );
        self.statics.insert((c.ty, c.ctor), name.clone());
        name
    }

    fn operand(&mut self, o: &Operand) -> String {
        match o {
            Operand::Var(v) => var(*v),
            Operand::Const(Const::Int(i, _)) => i.to_string(),
            Operand::Const(Const::Float(x)) => format!("0x{:016X}", x.to_bits()),
            Operand::Const(Const::Str(b)) => self.string_obj(b),
        }
    }

    fn operand_ty(f: &Function, o: &Operand) -> Ty {
        match o {
            Operand::Var(v) => f.ty(*v),
            Operand::Const(c) => c.ty(),
        }
    }

    fn typed_args(&mut self, f: &Function, args: &[Operand], tys: Option<&[Ty]>) -> String {
        let mut parts = Vec::new();
        for (i, a) in args.iter().enumerate() {
            let t = tys
                .and_then(|t| t.get(i).copied())
                .unwrap_or_else(|| Self::operand_ty(f, a));
            parts.push(format!("{} {}", llty(t), self.operand(a)));
        }
        parts.join(", ")
    }

    fn gep(c: &mut FnCtx<'_>, base: &str, off: usize) -> String {
        if off == 0 {
            return base.to_string();
        }
        let p = c.t();
        c.line(&format!(
            "{p} = getelementptr inbounds i8, ptr {base}, i64 {off}"
        ));
        p
    }

    fn emit_dup(&mut self, c: &mut FnCtx<'_>, o: &str) {
        if self.opts.debug_rt {
            c.line(&format!("call void @cirka_dup(ptr {o})"));
            return;
        }
        let rc = c.t();
        let pos = c.t();
        let (inc, slow, done) = (
            self.fresh_label("dup.inc"),
            self.fresh_label("dup.slow"),
            self.fresh_label("dup.done"),
        );
        c.line(&format!("{rc} = load i32, ptr {o}, align 8"));
        c.line(&format!("{pos} = icmp sgt i32 {rc}, 0"));
        c.line(&format!(
            "br i1 {pos}, label %{inc}, label %{slow}, !prof !0"
        ));
        c.label(&inc);
        let rc1 = c.t();
        c.line(&format!("{rc1} = add i32 {rc}, 1"));
        c.line(&format!("store i32 {rc1}, ptr {o}, align 8"));
        c.line(&format!("br label %{done}"));
        c.label(&slow);
        let neg = c.t();
        let atom = self.fresh_label("dup.atomic");
        c.line(&format!("{neg} = icmp slt i32 {rc}, 0"));
        c.line(&format!("br i1 {neg}, label %{atom}, label %{done}"));
        c.label(&atom);
        c.line(&format!("call void @cirka_dup(ptr {o})"));
        c.line(&format!("br label %{done}"));
        c.label(&done);
    }

    fn emit_drop(&mut self, c: &mut FnCtx<'_>, o: &str) {
        if self.opts.debug_rt {
            c.line(&format!("call void @cirka_drop(ptr {o})"));
            return;
        }
        let rc = c.t();
        let gt1 = c.t();
        let dec = self.fresh_label("drop.dec");
        let slow = self.fresh_label("drop.slow");
        let free = self.fresh_label("drop.free");
        let other = self.fresh_label("drop.other");
        let shared = self.fresh_label("drop.shared");
        let done = self.fresh_label("drop.done");
        c.line(&format!("{rc} = load i32, ptr {o}, align 8"));
        c.line(&format!("{gt1} = icmp sgt i32 {rc}, 1"));
        c.line(&format!(
            "br i1 {gt1}, label %{dec}, label %{slow}, !prof !0"
        ));
        c.label(&dec);
        let rc1 = c.t();
        c.line(&format!("{rc1} = sub i32 {rc}, 1"));
        c.line(&format!("store i32 {rc1}, ptr {o}, align 8"));
        c.line(&format!("br label %{done}"));
        c.label(&slow);
        let is1 = c.t();
        c.line(&format!("{is1} = icmp eq i32 {rc}, 1"));
        c.line(&format!("br i1 {is1}, label %{free}, label %{other}"));
        c.label(&free);
        c.line(&format!("call void @cirka_free_object(ptr {o})"));
        c.line(&format!("br label %{done}"));
        c.label(&other);
        let neg = c.t();
        c.line(&format!("{neg} = icmp slt i32 {rc}, 0"));
        c.line(&format!("br i1 {neg}, label %{shared}, label %{done}"));
        c.label(&shared);
        c.line(&format!("call void @cirka_dec_ref_slow(ptr {o})"));
        c.line(&format!("br label %{done}"));
        c.label(&done);
    }

    fn store_field(c: &mut FnCtx<'_>, base: &str, slot: usize, ty: Ty, val: &str) {
        let p = Self::gep(c, base, 8 + 8 * slot);
        c.line(&format!("store {} {val}, ptr {p}, align 8", llty(ty)));
    }

    fn load_field(c: &mut FnCtx<'_>, base: &str, slot: usize, ty: Ty) -> String {
        let p = Self::gep(c, base, 8 + 8 * slot);
        let r = c.t();
        c.line(&format!("{r} = load {}, ptr {p}, align 8", llty(ty)));
        r
    }

    fn emit_panic(&mut self, c: &mut FnCtx<'_>, msg: &str) {
        let (g, len) = self.panic_msg(msg);
        c.line(&format!("call void @cirka_panic(ptr {g}, i64 {len})"));
        c.line("unreachable");
    }

    /// `if cond { panic(msg) }`, continuing in a fresh block.
    fn check(&mut self, c: &mut FnCtx<'_>, cond: &str, msg: &str) {
        let bad = self.fresh_label("chk.fail");
        let ok = self.fresh_label("chk.ok");
        c.line(&format!(
            "br i1 {cond}, label %{bad}, label %{ok}, !prof !1"
        ));
        c.label(&bad);
        self.emit_panic(c, msg);
        c.label(&ok);
    }

    fn bounds(&mut self, c: &mut FnCtx<'_>, len: &str, idx: &str) {
        let bad = c.t();
        c.line(&format!("{bad} = icmp uge i64 {idx}, {len}"));
        self.check(c, &bad, "index out of bounds");
    }

    fn function(&mut self, f: &'m Function) {
        let mut c = FnCtx {
            f,
            body: String::new(),
            tmp: 0,
            cur: String::new(),
            phis: HashMap::new(),
            tokens: HashSet::new(),
        };
        for b in &f.blocks {
            for i in &b.instrs {
                if let Instr::Let {
                    var: Some(v),
                    rhs: Rhs::DropReuse(_),
                } = i
                {
                    c.tokens.insert(*v);
                }
            }
        }
        // Emit blocks; phi nodes are filled in afterwards via placeholders.
        let mut block_bodies = Vec::new();
        for (bi, b) in f.blocks.iter().enumerate() {
            c.body.clear();
            c.cur = bb_label(bi);
            let n = b.instrs.len();
            let mut skip_term = false;
            for (ii, ins) in b.instrs.iter().enumerate() {
                // `let r = call/apply ...; ret r` → musttail.
                if ii + 1 == n
                    && let (Instr::Let { var: Some(r), rhs }, Terminator::Ret(Operand::Var(rv))) =
                        (ins, &b.term)
                    && r == rv
                    && self.try_tail(&mut c, rhs)
                {
                    skip_term = true;
                    continue;
                }
                self.instr(&mut c, ins);
            }
            if !skip_term {
                self.term(&mut c, bi, &b.term);
            }
            block_bodies.push(std::mem::take(&mut c.body));
        }
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("{} {}", llty(f.ty(p.var)), var(p.var)))
            .collect();
        let _ = writeln!(
            self.out,
            "define tailcc {} {}({}) {{",
            llty(f.ret),
            mangle(&f.name),
            params.join(", ")
        );
        for (bi, body) in block_bodies.iter().enumerate() {
            let _ = writeln!(self.out, "{}:", bb_label(bi));
            if let Some(inc) = c.phis.get(&bi) {
                for (k, p) in f.blocks[bi].params.iter().enumerate() {
                    let parts: Vec<String> = inc
                        .iter()
                        .map(|(vals, pred)| format!("[ {}, %{pred} ]", vals[k]))
                        .collect();
                    let _ = writeln!(
                        self.out,
                        "  {} = phi {} {}",
                        var(*p),
                        llty(f.ty(*p)),
                        parts.join(", ")
                    );
                }
            }
            self.out.push_str(body);
        }
        self.out.push_str("}\n\n");
    }

    fn try_tail(&mut self, c: &mut FnCtx<'_>, rhs: &Rhs) -> bool {
        let f = c.f;
        match rhs {
            Rhs::Call { func, args } => {
                let Some(g) = self.funcs.get(func.as_str()).copied() else {
                    return false;
                };
                if g.ret != f.ret {
                    return false;
                }
                let tys = g.param_tys();
                let a = self.typed_args(f, args, Some(&tys));
                let r = c.t();
                c.line(&format!(
                    "{r} = musttail call tailcc {} {}({a})",
                    llty(g.ret),
                    mangle(func)
                ));
                c.line(&format!("ret {} {r}", llty(g.ret)));
                true
            }
            Rhs::Apply { clo, args } if f.ret == Ty::Ptr => {
                let a = self.typed_args(f, args, None);
                let r = c.t();
                c.line(&format!(
                    "{r} = musttail call tailcc ptr @cirka_apply_{}(ptr {}, {a})",
                    args.len(),
                    var(*clo)
                ));
                c.line(&format!("ret ptr {r}"));
                true
            }
            _ => false,
        }
    }

    fn instr(&mut self, c: &mut FnCtx<'_>, ins: &Instr) {
        match ins {
            Instr::Dup(v) => self.emit_dup(c, &var(*v)),
            Instr::Drop(v) => {
                if c.tokens.contains(v) {
                    c.line(&format!("call void @cirka_free_raw(ptr {})", var(*v)));
                } else {
                    self.emit_drop(c, &var(*v));
                }
            }
            Instr::Set {
                obj,
                ctor,
                field,
                val,
            } => {
                let def = self.m.ctor(*ctor);
                let ty = def.fields[*field as usize].ty;
                let v = self.operand(val);
                Self::store_field(c, &var(*obj), def.slot(*field as usize), ty, &v);
            }
            Instr::Let { var: x, rhs } => {
                let dst = match x {
                    Some(v) => var(*v),
                    None => c.t(),
                };
                self.rhs(c, &dst, x.is_some(), rhs);
            }
        }
    }

    fn rhs(&mut self, c: &mut FnCtx<'_>, dst: &str, bound: bool, rhs: &Rhs) {
        let f = c.f;
        let m = self.m;
        match rhs {
            Rhs::Lit(k) => {
                let v = self.operand(&Operand::Const(k.clone()));
                match k {
                    Const::Int(_, t) => c.line(&format!("{dst} = add {} {v}, 0", llty(*t))),
                    Const::Float(_) => c.line(&format!("{dst} = fadd double {v}, 0.0")),
                    Const::Str(_) => c.line(&format!("{dst} = getelementptr i8, ptr {v}, i64 0")),
                }
            }
            Rhs::Prim(p, args) => self.prim(c, dst, *p, args),
            Rhs::Alloc { ctor, args, reuse } => {
                let def = m.ctor(*ctor);
                if def.fields.is_empty() {
                    let s = self.static_con(*ctor);
                    c.line(&format!("{dst} = getelementptr i8, ptr {s}, i64 0"));
                    return;
                }
                let size = def.size();
                let obj = match reuse {
                    None => {
                        let p = c.t();
                        c.line(&format!("{p} = call ptr @cirka_alloc(i64 {size})"));
                        p
                    }
                    Some(tok) => {
                        let tok = var(*tok);
                        let isnull = c.t();
                        let fresh = self.fresh_label("alloc.fresh");
                        let reuse_l = self.fresh_label("alloc.reuse");
                        let join = self.fresh_label("alloc.join");
                        c.line(&format!("{isnull} = icmp eq ptr {tok}, null"));
                        c.line(&format!("br i1 {isnull}, label %{fresh}, label %{reuse_l}"));
                        c.label(&fresh);
                        let p1 = c.t();
                        c.line(&format!("{p1} = call ptr @cirka_alloc(i64 {size})"));
                        c.line(&format!("br label %{join}"));
                        c.label(&reuse_l);
                        c.line(&format!("br label %{join}"));
                        c.label(&join);
                        let p = c.t();
                        c.line(&format!(
                            "{p} = phi ptr [ {p1}, %{fresh} ], [ {tok}, %{reuse_l} ]"
                        ));
                        p
                    }
                };
                c.line(&format!(
                    "store i64 {}, ptr {obj}, align 8",
                    header_word(1, def.tag, def.nptr(), kind::CON)
                ));
                for (i, a) in args.iter().enumerate() {
                    let v = self.operand(a);
                    Self::store_field(c, &obj, def.slot(i), def.fields[i].ty, &v);
                }
                c.line(&format!("{dst} = getelementptr i8, ptr {obj}, i64 0"));
            }
            Rhs::Proj { obj, ctor, field } => {
                let def = m.ctor(*ctor);
                let ty = def.fields[*field as usize].ty;
                let p = Self::gep(c, &var(*obj), 8 + 8 * def.slot(*field as usize));
                c.line(&format!("{dst} = load {}, ptr {p}, align 8", llty(ty)));
            }
            Rhs::Call { func, args } => {
                let Some(g) = self.funcs.get(func.as_str()).copied() else {
                    panic!("ICE: call to unknown function {func}");
                };
                let tys = g.param_tys();
                let a = self.typed_args(f, args, Some(&tys));
                c.line(&format!(
                    "{dst} = call tailcc {} {}({a})",
                    llty(g.ret),
                    mangle(func)
                ));
            }
            Rhs::Apply { clo, args } => {
                let a = self.typed_args(f, args, None);
                c.line(&format!(
                    "{dst} = call tailcc ptr @cirka_apply_{}(ptr {}, {a})",
                    args.len(),
                    var(*clo)
                ));
            }
            Rhs::MkClosure { func, args } | Rhs::MkThunk { func, args } => {
                let is_clo = matches!(rhs, Rhs::MkClosure { .. });
                let g = self.funcs[func.as_str()];
                let tys = g.param_tys();
                let arity = g.params.len() - args.len();
                let nptr = tys[..args.len()].iter().filter(|t| t.is_ptr()).count();
                let size = 16 + 8 * args.len();
                let obj = c.t();
                c.line(&format!("{obj} = call ptr @cirka_alloc(i64 {size})"));
                let (k, tag, stub) = if is_clo {
                    self.clo_stubs.insert(func.clone(), args.len());
                    (
                        kind::FUN,
                        arity as u32,
                        format!("@\"{}$clo\"", &mangle(func)[2..mangle(func).len() - 1]),
                    )
                } else {
                    self.thunk_stubs.insert(func.clone(), ());
                    (
                        kind::THUNK,
                        0,
                        format!("@\"{}$thk\"", &mangle(func)[2..mangle(func).len() - 1]),
                    )
                };
                c.line(&format!(
                    "store i64 {}, ptr {obj}, align 8",
                    header_word(1, tag, nptr, k)
                ));
                Self::store_field(c, &obj, 0, Ty::Ptr, &stub);
                for (i, a) in args.iter().enumerate() {
                    let v = self.operand(a);
                    let slot = capture_slot(&tys[..args.len()], i);
                    Self::store_field(c, &obj, 1 + slot, tys[i], &v);
                }
                c.line(&format!("{dst} = getelementptr i8, ptr {obj}, i64 0"));
            }
            Rhs::Force(v) => {
                let o = var(*v);
                let kp = Self::gep(c, &o, 7);
                let k = c.t();
                c.line(&format!("{k} = load i8, ptr {kp}, align 1"));
                let rel = c.t();
                c.line(&format!("{rel} = sub i8 {k}, {}", kind::THUNK));
                let lazy = c.t();
                c.line(&format!("{lazy} = icmp ult i8 {rel}, 3"));
                let slow = self.fresh_label("force.slow");
                let done = self.fresh_label("force.done");
                let start = c.cur.clone();
                c.line(&format!("br i1 {lazy}, label %{slow}, label %{done}"));
                c.label(&slow);
                let r = c.t();
                c.line(&format!("{r} = call ptr @cirka_force(ptr {o})"));
                c.line(&format!("br label %{done}"));
                c.label(&done);
                c.line(&format!(
                    "{dst} = phi ptr [ {o}, %{start} ], [ {r}, %{slow} ]"
                ));
            }
            Rhs::DropReuse(v) => {
                c.line(&format!(
                    "{dst} = call ptr @cirka_drop_reuse(ptr {})",
                    var(*v)
                ));
            }
            Rhs::Extern { func, args } => {
                let d = m.extern_decl(func).expect("ICE: undeclared extern");
                let tys: Vec<Ty> = d.params.iter().map(|p| p.0).collect();
                let a = self.typed_args(f, args, Some(&tys));
                match d.ret {
                    Some(t) => c.line(&format!("{dst} = call {} @{func}({a})", llty(t))),
                    None => {
                        c.line(&format!("call void @{func}({a})"));
                        if bound {
                            c.line(&format!("{dst} = add i64 0, 0"));
                        }
                    }
                }
            }
            Rhs::Global(gname) => {
                c.line(&format!(
                    "{dst} = getelementptr i8, ptr @\"g.{gname}\", i64 0"
                ));
            }
        }
    }

    fn prim(&mut self, c: &mut FnCtx<'_>, dst: &str, p: Prim, args: &[Operand]) {
        use Prim::*;
        let a: Vec<String> = args.iter().map(|o| self.operand(o)).collect();
        let bin = |c: &mut FnCtx<'_>, op: &str, ty: &str| {
            c.line(&format!("{dst} = {op} {ty} {}, {}", a[0], a[1]))
        };
        let cmp = |c: &mut FnCtx<'_>, op: &str, ty: &str| {
            let t = c.t();
            c.line(&format!("{t} = {op} {ty} {}, {}", a[0], a[1]));
            c.line(&format!("{dst} = zext i1 {t} to i64"));
        };
        match p {
            Add => bin(c, "add", "i64"),
            Sub => bin(c, "sub", "i64"),
            Mul => bin(c, "mul", "i64"),
            Div | Rem => {
                let z = c.t();
                c.line(&format!("{z} = icmp eq i64 {}, 0", a[1]));
                self.check(c, &z, "divide by zero");
                // x / -1 overflows for i64::MIN; follow wrapping semantics.
                let m1 = c.t();
                c.line(&format!("{m1} = icmp eq i64 {}, -1", a[1]));
                let safe = c.t();
                c.line(&format!("{safe} = select i1 {m1}, i64 1, i64 {}", a[1]));
                let q = c.t();
                let op = if p == Div { "sdiv" } else { "srem" };
                c.line(&format!("{q} = {op} i64 {}, {safe}", a[0]));
                let alt = c.t();
                if p == Div {
                    c.line(&format!("{alt} = sub i64 0, {}", a[0]));
                } else {
                    c.line(&format!("{alt} = add i64 0, 0"));
                }
                c.line(&format!("{dst} = select i1 {m1}, i64 {alt}, i64 {q}"));
            }
            Neg => c.line(&format!("{dst} = sub i64 0, {}", a[0])),
            And => bin(c, "and", "i64"),
            Or => bin(c, "or", "i64"),
            Xor => bin(c, "xor", "i64"),
            Shl | Shr | LShr => {
                let s = c.t();
                c.line(&format!("{s} = and i64 {}, 63", a[1]));
                let op = match p {
                    Shl => "shl",
                    Shr => "ashr",
                    _ => "lshr",
                };
                c.line(&format!("{dst} = {op} i64 {}, {s}", a[0]));
            }
            Eq => cmp(c, "icmp eq", "i64"),
            Ne => cmp(c, "icmp ne", "i64"),
            Lt => cmp(c, "icmp slt", "i64"),
            Le => cmp(c, "icmp sle", "i64"),
            Gt => cmp(c, "icmp sgt", "i64"),
            Ge => cmp(c, "icmp sge", "i64"),
            FAdd => bin(c, "fadd", "double"),
            FSub => bin(c, "fsub", "double"),
            FMul => bin(c, "fmul", "double"),
            FDiv => bin(c, "fdiv", "double"),
            FNeg => c.line(&format!("{dst} = fneg double {}", a[0])),
            FEq => cmp(c, "fcmp oeq", "double"),
            FNe => cmp(c, "fcmp une", "double"),
            FLt => cmp(c, "fcmp olt", "double"),
            FLe => cmp(c, "fcmp ole", "double"),
            FGt => cmp(c, "fcmp ogt", "double"),
            FGe => cmp(c, "fcmp oge", "double"),
            I64ToF64 => c.line(&format!("{dst} = sitofp i64 {} to double", a[0])),
            F64ToI64 => c.line(&format!(
                "{dst} = call i64 @llvm.fptosi.sat.i64.f64(double {})",
                a[0]
            )),
            I64ToI32 => c.line(&format!("{dst} = trunc i64 {} to i32", a[0])),
            I32ToI64 => c.line(&format!("{dst} = sext i32 {} to i64", a[0])),
            I64ToI8 => c.line(&format!("{dst} = trunc i64 {} to i8", a[0])),
            I8ToI64 => c.line(&format!("{dst} = sext i8 {} to i64", a[0])),
            F64Bits => c.line(&format!("{dst} = bitcast double {} to i64", a[0])),
            BitsF64 => c.line(&format!("{dst} = bitcast i64 {} to double", a[0])),
            PtrEq => cmp(c, "icmp eq", "ptr"),
            IsUnique => {
                let rc = c.t();
                c.line(&format!("{rc} = load i32, ptr {}, align 8", a[0]));
                let t = c.t();
                c.line(&format!("{t} = icmp eq i32 {rc}, 1"));
                c.line(&format!("{dst} = zext i1 {t} to i64"));
            }
            BytesNew => c.line(&format!("{dst} = call ptr @cirka_bytes_new(i64 {})", a[0])),
            BytesLen => {
                let l = Self::load_field(c, &a[0], 0, Ty::I64);
                c.line(&format!("{dst} = add i64 {l}, 0"));
            }
            BytesGet | BytesSet => {
                let len = Self::load_field(c, &a[0], 0, Ty::I64);
                self.bounds(c, &len, &a[1]);
                let base = Self::gep(c, &a[0], 16);
                let ep = c.t();
                c.line(&format!(
                    "{ep} = getelementptr inbounds i8, ptr {base}, i64 {}",
                    a[1]
                ));
                let p_ = ep;
                if p == BytesGet {
                    let b = c.t();
                    c.line(&format!("{b} = load i8, ptr {p_}, align 1"));
                    c.line(&format!("{dst} = zext i8 {b} to i64"));
                } else {
                    let b = c.t();
                    c.line(&format!("{b} = trunc i64 {} to i8", a[2]));
                    c.line(&format!("store i8 {b}, ptr {p_}, align 1"));
                    c.line(&format!("{dst} = add i64 0, 0"));
                }
            }
            BytesData => {
                let base = Self::gep(c, &a[0], 16);
                c.line(&format!("{dst} = ptrtoint ptr {base} to i64"));
            }
            ArrayNew => c.line(&format!(
                "{dst} = call ptr @cirka_array_new(i64 {}, ptr {})",
                a[0], a[1]
            )),
            ArrayLen => {
                let l = Self::load_field(c, &a[0], 0, Ty::I64);
                c.line(&format!("{dst} = add i64 {l}, 0"));
            }
            ArrayGet | ArraySet => {
                let len = Self::load_field(c, &a[0], 0, Ty::I64);
                self.bounds(c, &len, &a[1]);
                let base = Self::gep(c, &a[0], 16);
                let ep = c.t();
                c.line(&format!(
                    "{ep} = getelementptr inbounds ptr, ptr {base}, i64 {}",
                    a[1]
                ));
                if p == ArrayGet {
                    c.line(&format!("{dst} = load ptr, ptr {ep}, align 8"));
                } else {
                    let old = c.t();
                    c.line(&format!("{old} = load ptr, ptr {ep}, align 8"));
                    c.line(&format!("store ptr {}, ptr {ep}, align 8", a[2]));
                    self.emit_drop(c, &old);
                    c.line(&format!("{dst} = add i64 0, 0"));
                }
            }
        }
    }

    fn term(&mut self, c: &mut FnCtx<'_>, bi: usize, t: &Terminator) {
        let f = c.f;
        let _ = bi;
        match t {
            Terminator::Ret(o) => {
                let v = self.operand(o);
                c.line(&format!("ret {} {v}", llty(f.ret)));
            }
            Terminator::Jump(b, args) => {
                let vals: Vec<String> = args.iter().map(|a| self.operand(a)).collect();
                let pred = c.cur.clone();
                c.phis.entry(b.0 as usize).or_default().push((vals, pred));
                c.line(&format!("br label %{}", bb_label(b.0 as usize)));
            }
            Terminator::Switch {
                scrut,
                arms,
                default,
            } => {
                let s = var(*scrut);
                let dflt = match default {
                    Some(d) => bb_label(d.0 as usize),
                    None => self.fresh_label("sw.none"),
                };
                let sty = f.ty(*scrut);
                let (val, ty) = if sty == Ty::Ptr {
                    let tp = Self::gep(c, &s, 4);
                    let tag = c.t();
                    c.line(&format!("{tag} = load i16, ptr {tp}, align 4"));
                    (tag, "i16")
                } else {
                    (s.clone(), llty(sty))
                };
                let mut cases = Vec::new();
                for (case, b) in arms {
                    let k = match case {
                        Case::Ctor(ct) => self.m.ctor(*ct).tag as i64,
                        Case::Int(i) => *i,
                    };
                    cases.push(format!("{ty} {k}, label %{}", bb_label(b.0 as usize)));
                }
                c.line(&format!(
                    "switch {ty} {val}, label %{dflt} [ {} ]",
                    cases.join(" ")
                ));
                if default.is_none() {
                    c.label(&dflt);
                    self.emit_panic(c, "no matching switch arm");
                }
            }
            Terminator::TailCall { func, args } => {
                let g = self.funcs[func.as_str()];
                let tys = g.param_tys();
                let a = self.typed_args(f, args, Some(&tys));
                let r = c.t();
                c.line(&format!(
                    "{r} = musttail call tailcc {} {}({a})",
                    llty(g.ret),
                    mangle(func)
                ));
                c.line(&format!("ret {} {r}", llty(g.ret)));
            }
            Terminator::Panic(msg) => self.emit_panic(c, msg),
            Terminator::Unreachable => c.line("unreachable"),
        }
    }

    /// `f$clo(env, a1..an)`: entry stub of closures over `f` with `ncap`
    /// captured values.
    fn closure_stub(&mut self, fname: &str, ncap: usize) {
        let g = self.funcs[fname];
        let tys = g.param_tys();
        let arity = g.params.len() - ncap;
        let mn = mangle(fname);
        let stub = format!("@\"{}$clo\"", &mn[2..mn.len() - 1]);
        let mut c = FnCtx {
            f: g,
            body: String::new(),
            tmp: 0,
            cur: "entry".into(),
            phis: HashMap::new(),
            tokens: HashSet::new(),
        };
        let mut caps = Vec::new();
        for i in 0..ncap {
            let slot = capture_slot(&tys[..ncap], i);
            caps.push(Self::load_field(&mut c, "%env", 1 + slot, tys[i]));
        }
        let borrowed = g.params[..ncap].iter().any(|p| p.own == Own::Borrowed);
        let args: Vec<String> = (0..arity).map(|i| format!("ptr %a{i}")).collect();
        let mut call_args: Vec<String> = caps
            .iter()
            .enumerate()
            .map(|(i, v)| format!("{} {v}", llty(tys[i])))
            .collect();
        call_args.extend(args.iter().cloned());
        if !borrowed {
            let rc = c.t();
            c.line(&format!("{rc} = load i32, ptr %env, align 8"));
            let u = c.t();
            c.line(&format!("{u} = icmp eq i32 {rc}, 1"));
            c.line(&format!("br i1 {u}, label %unique, label %shared"));
            c.label("unique");
            c.line("call void @cirka_free_raw(ptr %env)");
            c.line("br label %go");
            c.label("shared");
            for (i, v) in caps.iter().enumerate() {
                if tys[i].is_ptr() {
                    self.emit_dup(&mut c, v);
                }
            }
            self.emit_drop(&mut c, "%env");
            c.line("br label %go");
            c.label("go");
            let r = c.t();
            c.line(&format!(
                "{r} = musttail call tailcc ptr {mn}({})",
                call_args.join(", ")
            ));
            c.line(&format!("ret ptr {r}"));
        } else {
            for (i, v) in caps.iter().enumerate() {
                if tys[i].is_ptr() && g.params[i].own == Own::Owned {
                    self.emit_dup(&mut c, v);
                }
            }
            let r = c.t();
            c.line(&format!(
                "{r} = call tailcc ptr {mn}({})",
                call_args.join(", ")
            ));
            self.emit_drop(&mut c, "%env");
            c.line(&format!("ret ptr {r}"));
        }
        let _ = writeln!(
            self.out,
            "define internal tailcc ptr {stub}(ptr %env{}) {{\nentry:\n{}}}\n",
            args.iter().map(|a| format!(", {a}")).collect::<String>(),
            c.body
        );
    }

    /// `f$thk(t)`: C-ABI entry stub called by `cirka_force`.
    fn thunk_stub(&mut self, fname: &str) {
        let g = self.funcs[fname];
        let tys = g.param_tys();
        let mn = mangle(fname);
        let stub = format!("@\"{}$thk\"", &mn[2..mn.len() - 1]);
        let mut c = FnCtx {
            f: g,
            body: String::new(),
            tmp: 0,
            cur: "entry".into(),
            phis: HashMap::new(),
            tokens: HashSet::new(),
        };
        let mut call_args = Vec::new();
        for i in 0..tys.len() {
            let slot = capture_slot(&tys, i);
            let v = Self::load_field(&mut c, "%t", 1 + slot, tys[i]);
            if tys[i].is_ptr() && g.params[i].own == Own::Owned {
                self.emit_dup(&mut c, &v);
            }
            call_args.push(format!("{} {v}", llty(tys[i])));
        }
        let r = c.t();
        c.line(&format!(
            "{r} = call tailcc ptr {mn}({})",
            call_args.join(", ")
        ));
        c.line(&format!("ret ptr {r}"));
        let _ = writeln!(
            self.out,
            "define internal ptr {stub}(ptr %t) {{\nentry:\n{}}}\n",
            c.body
        );
    }

    /// Generic eval/apply for `n` arguments.
    fn apply_helper(&mut self, n: usize) {
        let mut s = String::new();
        let args: Vec<String> = (1..=n).map(|i| format!("%a{i}")).collect();
        let targs = |xs: &[String]| {
            xs.iter()
                .map(|a| format!("ptr {a}"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(
            s,
            "define internal tailcc ptr @cirka_apply_{n}(ptr %f, {}) {{",
            targs(&args)
        );
        s.push_str("entry:\n");
        s.push_str(
            "  %kp = getelementptr inbounds i8, ptr %f, i64 7\n  %k = load i8, ptr %kp, align 1\n",
        );
        let _ = writeln!(
            s,
            "  switch i8 %k, label %other [ i8 {}, label %fun i8 {}, label %pap ]",
            kind::FUN,
            kind::PAP
        );
        // FUN
        s.push_str("fun:\n  %arp = getelementptr inbounds i8, ptr %f, i64 4\n  %ar16 = load i16, ptr %arp, align 4\n  %ar = zext i16 %ar16 to i64\n");
        s.push_str("  %cp = getelementptr inbounds i8, ptr %f, i64 8\n  %code = load ptr, ptr %cp, align 8\n");
        let mut cases = vec![format!("i64 {n}, label %exact")];
        for k in 1..n {
            cases.push(format!("i64 {k}, label %over{k}"));
        }
        let _ = writeln!(s, "  switch i64 %ar, label %under [ {} ]", cases.join(" "));
        let _ = writeln!(
            s,
            "exact:\n  %re = musttail call tailcc ptr %code(ptr %f, {})\n  ret ptr %re",
            targs(&args)
        );
        for k in 1..n {
            let _ = writeln!(
                s,
                "over{k}:\n  %ro{k} = call tailcc ptr %code(ptr %f, {})\n  %rr{k} = musttail call tailcc ptr @cirka_apply_{}(ptr %ro{k}, {})\n  ret ptr %rr{k}",
                targs(&args[..k]),
                n - k,
                targs(&args[k..])
            );
        }
        s.push_str("under:\n");
        let _ = writeln!(s, "  %arr = alloca [{n} x ptr], align 8");
        for (i, a) in args.iter().enumerate() {
            let _ = writeln!(
                s,
                "  %ap{i} = getelementptr inbounds ptr, ptr %arr, i64 {i}\n  store ptr {a}, ptr %ap{i}, align 8"
            );
        }
        let _ = writeln!(
            s,
            "  %newpap = call ptr @cirka_mk_pap(ptr %f, i64 {n}, ptr %arr)\n  ret ptr %newpap"
        );
        // PAP
        s.push_str("pap:\n  %mp = getelementptr inbounds i8, ptr %f, i64 4\n  %m16 = load i16, ptr %mp, align 4\n  %m = zext i16 %m16 to i64\n");
        s.push_str(
            "  %gp = getelementptr inbounds i8, ptr %f, i64 8\n  %g = load ptr, ptr %gp, align 8\n",
        );
        s.push_str("  %garp = getelementptr inbounds i8, ptr %g, i64 4\n  %gar16 = load i16, ptr %garp, align 4\n  %gar = zext i16 %gar16 to i64\n");
        s.push_str("  %rem = sub i64 %gar, %m\n");
        let mut rcases = Vec::new();
        for k in 1..n {
            rcases.push(format!("i64 {k}, label %pover{k}"));
        }
        let _ = writeln!(
            s,
            "  switch i64 %rem, label %punpack [ {} ]",
            rcases.join(" ")
        );
        for k in 1..n {
            let _ = writeln!(
                s,
                "pover{k}:\n  %pr{k} = call tailcc ptr @cirka_apply_{k}(ptr %f, {})\n  %prr{k} = musttail call tailcc ptr @cirka_apply_{}(ptr %pr{k}, {})\n  ret ptr %prr{k}",
                targs(&args[..k]),
                n - k,
                targs(&args[k..])
            );
        }
        // rem >= n: unpack the PAP and apply the function to all arguments.
        let mut jcases = Vec::new();
        for j in 1..=MAX_CLOSURE_ARITY.saturating_sub(n) {
            jcases.push(format!("i64 {j}, label %unpack{j}"));
        }
        let (bad, _) = self.panic_msg("bad partial application");
        let _ = writeln!(
            s,
            "punpack:\n  switch i64 %m, label %bad [ {} ]",
            jcases.join(" ")
        );
        let _ = writeln!(
            s,
            "bad:\n  call void @cirka_panic(ptr {bad}, i64 23)\n  unreachable"
        );
        for j in 1..=MAX_CLOSURE_ARITY.saturating_sub(n) {
            let ys: Vec<String> = (1..=j).map(|i| format!("%y{j}_{i}")).collect();
            let _ = writeln!(s, "unpack{j}:");
            for (i, y) in ys.iter().enumerate() {
                let _ = writeln!(
                    s,
                    "  %yp{j}_{i} = getelementptr inbounds i8, ptr %f, i64 {}\n  {y} = load ptr, ptr %yp{j}_{i}, align 8",
                    16 + 8 * i
                );
            }
            let _ = writeln!(
                s,
                "  %rc{j} = load i32, ptr %f, align 8\n  %u{j} = icmp eq i32 %rc{j}, 1\n  br i1 %u{j}, label %uq{j}, label %sh{j}"
            );
            let _ = writeln!(
                s,
                "uq{j}:\n  call void @cirka_free_raw(ptr %f)\n  br label %go{j}"
            );
            let _ = writeln!(s, "sh{j}:\n  call void @cirka_dup(ptr %g)");
            for y in &ys {
                let _ = writeln!(s, "  call void @cirka_dup(ptr {y})");
            }
            let _ = writeln!(s, "  call void @cirka_drop(ptr %f)\n  br label %go{j}");
            let mut all = ys.clone();
            all.extend(args.iter().cloned());
            let _ = writeln!(
                s,
                "go{j}:\n  %ru{j} = musttail call tailcc ptr @cirka_apply_{}(ptr %g, {})\n  ret ptr %ru{j}",
                j + n,
                targs(&all)
            );
        }
        // THUNK / IND: evaluate, then apply.
        let _ = writeln!(
            s,
            "other:\n  %v = call ptr @cirka_force(ptr %f)\n  %rv = musttail call tailcc ptr @cirka_apply_{n}(ptr %v, {})\n  ret ptr %rv\n}}\n",
            targs(&args)
        );
        self.out.push_str(&s);
    }

    fn entry_and_cafs(&mut self) {
        let m = self.m;
        for gl in &m.globals {
            let mn = mangle(&gl.init);
            let stub = format!("@\"{}$thk\"", &mn[2..mn.len() - 1]);
            let _ = writeln!(
                self.globals,
                "@\"g.{}\" = internal global {{ i64, ptr }} {{ i64 {}, ptr {stub} }}, align 8",
                gl.name,
                header_word(0, 0, 0, kind::THUNK)
            );
        }
        let roots: Vec<String> = m
            .globals
            .iter()
            .map(|g| format!("ptr @\"g.{}\"", g.name))
            .collect();
        let _ = writeln!(
            self.globals,
            "@cirka_caf_roots = global [{} x ptr] [{}], align 8\n@cirka_caf_count = global i64 {}",
            roots.len(),
            roots.join(", "),
            roots.len()
        );
        if let Some(main) = self.funcs.get("main") {
            let ret = main.ret;
            let _ = writeln!(self.out, "define i64 @cirka_main() {{\nentry:");
            let _ = writeln!(
                self.out,
                "  %r = call tailcc {} {}()",
                llty(ret),
                mangle("main")
            );
            match ret {
                Ty::I64 => self.out.push_str("  ret i64 %r\n}\n"),
                Ty::I32 | Ty::I8 => {
                    let _ = writeln!(
                        self.out,
                        "  %x = sext {} %r to i64\n  ret i64 %x\n}}",
                        llty(ret)
                    );
                }
                _ => self.out.push_str("  ret i64 0\n}\n"),
            }
        }
        self.out.push_str("\n!0 = !{!\"branch_weights\", i32 2000, i32 1}\n!1 = !{!\"branch_weights\", i32 1, i32 2000}\n");
    }
}

/// Slot (word index after the code pointer) of captured value `i` given
/// the captured types: pointers first, then scalars.
fn capture_slot(tys: &[Ty], i: usize) -> usize {
    if tys[i].is_ptr() {
        tys[..i].iter().filter(|t| t.is_ptr()).count()
    } else {
        tys.iter().filter(|t| t.is_ptr()).count() + tys[..i].iter().filter(|t| !t.is_ptr()).count()
    }
}
